#!/usr/bin/env python3
"""Generates the REC-1 wiring diagram (SVG) from the wiring table.

    python3 tools/make_schematic.py        ->  SCHEMATIC.svg

This is a *wiring diagram* drawn from the same data as WIRING.md.  It is not
an EDA/netlist project: it was not checked by a DRC or netlist tool, so it
must not be used as evidence that the design is "manufacturing ready".
"""

import os
import xml.sax.saxutils as sax

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "SCHEMATIC.svg")

W, H = 1600, 1090

BG = "#0f1216"
PANEL = "#1a1f27"
LINE = "#5c6876"
TXT = "#e6eaf0"
MUTED = "#8b97a6"
SIG = "#d6a13a"
I2C = "#4f9de0"
PWR = "#d05a5a"
GND = "#7d8894"


def esc(text):
    return sax.escape(str(text))


def block(x, y, w, h, title, subtitle):
    out = [
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="8" fill="{PANEL}" '
        f'stroke="{LINE}" stroke-width="1.5"/>',
        f'<text x="{x + 14}" y="{y + 26}" fill="{TXT}" font-family="Helvetica,Arial" '
        f'font-size="16" font-weight="bold">{esc(title)}</text>',
    ]
    if subtitle:
        out.append(
            f'<text x="{x + 14}" y="{y + 45}" fill="{MUTED}" font-family="Helvetica,Arial" '
            f'font-size="12">{esc(subtitle)}</text>')
    return "\n".join(out)


def pin(x, y, label, color=TXT, anchor="start"):
    dx = 8 if anchor == "start" else -8
    return (
        f'<circle cx="{x}" cy="{y}" r="3.5" fill="{color}"/>'
        f'<text x="{x + dx}" y="{y + 4}" fill="{color}" font-family="Menlo,Consolas,monospace" '
        f'font-size="12" text-anchor="{anchor}">{esc(label)}</text>'
    )


def wire(x1, y1, x2, y2, color=SIG):
    return (f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{color}" '
            f'stroke-width="2"/>')


def gnd_symbol(x, y):
    """IEEE style ground symbol below the pin."""
    return (
        f'<line x1="{x}" y1="{y}" x2="{x}" y2="{y + 10}" stroke="{GND}" stroke-width="2"/>'
        f'<polygon points="{x - 7},{y + 10} {x + 7},{y + 10} {x},{y + 20}" fill="{GND}"/>'
        f'<line x1="{x - 9}" y1="{y + 24}" x2="{x + 9}" y2="{y + 24}" stroke="{GND}" stroke-width="2"/>'
        f'<line x1="{x - 5}" y1="{y + 28}" x2="{x + 5}" y2="{y + 28}" stroke="{GND}" stroke-width="2"/>'
    )


def text(x, y, content, color=MUTED, size=12, anchor="start"):
    return (f'<text x="{x}" y="{y}" fill="{color}" font-family="Menlo,Consolas,monospace" '
            f'font-size="{size}" text-anchor="{anchor}">{esc(content)}</text>')


def build():
    p = []
    p.append(f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" '
             f'viewBox="0 0 {W} {H}">')
    p.append(f'<rect width="{W}" height="{H}" fill="{BG}"/>')
    p.append('<text x="40" y="48" fill="#e6eaf0" font-family="Helvetica,Arial" font-size="25" '
             'font-weight="bold">REC-1 desk recording controller - wiring diagram</text>')
    p.append('<text x="40" y="72" fill="#8b97a6" font-family="Helvetica,Arial" font-size="12.5">'
             'generated by tools/make_schematic.py - reference wiring diagram, '
             'not a verified EDA netlist</text>')

    # ---------------------------------------------------------------- MCU --
    mx, my, mw, mh = 60, 150, 430, 700
    ox, ow = 880, 300
    p.append(block(mx, my, mw, mh, "QT Py RP2040 (Adafruit 4900)",
                   "RP2040 - 3.3 V logic - USB-C native CDC - STEMMA QT = I2C1 "
                   "(GPIO22/23)"))

    signals = [
        # (mcu pin y, peripheral block, pin y, colour, mcu label, wire label)
        (200, "3V3 (QT pin 2)", PWR, "3V3 (board LDO)"),
        (270, "SDA1 / GPIO22 (QT pin 3)", I2C, "SDA"),
        (340, "SCL1 / GPIO23 (QT pin 4)", I2C, "SCL"),
        (480, "A2 / GPIO27 (JP1 pad 3)", SIG, "REC"),
        (590, "A3 / GPIO26 (JP1 pad 4)", SIG, "SCENE"),
        (730, "A1 / GPIO28 (JP1 pad 2)", SIG, "LED + 220 R"),
    ]
    for y, label, color, _name in signals:
        p.append(pin(mx + mw, my + y, label, color, "end"))
    p.append(f'<circle cx="{mx + mw}" cy="{my + 670}" r="3.5" fill="{GND}"/>')
    p.append(text(mx + mw - 8, my + 674, "GND (JP3 pad 6)", GND, 12, "end"))
    p.append(gnd_symbol(mx + mw, my + 670))
    p.append(f'<circle cx="{mx + 150}" cy="{my + mh}" r="3.5" fill="{GND}"/>')
    p.append(text(mx + 160, my + mh + 4, "USB-C: 5 V + GND", GND, 12))

    # --------------------------------------------------------- peripherals --
    p.append(block(ox, my + 150, ow, 260, "OLED 938 (Adafruit)",
                   '1.3" 128x64 SSD1306 - STEMMA QT - I2C 0x3C'))
    p.append(pin(ox, my + 200, "", PWR))
    p.append(pin(ox, my + 270, "", I2C))
    p.append(pin(ox, my + 340, "", I2C))
    p.append(f'<circle cx="{ox + 40}" cy="{my + 410}" r="3.5" fill="{GND}"/>')
    p.append(text(ox + 48, my + 414, "GND (pin 1)", GND))
    p.append(gnd_symbol(ox + 40, my + 410))

    p.append(block(ox, my + 400, ow, 120, "REC button (6 mm tact)",
                   "press fit in the face panel, internal pull-up"))
    p.append(pin(ox, my + 480, "", SIG))
    p.append(f'<circle cx="{ox + 40}" cy="{my + 520}" r="3.5" fill="{GND}"/>')
    p.append(text(ox + 48, my + 524, "GND", GND))
    p.append(gnd_symbol(ox + 40, my + 520))

    p.append(block(ox, my + 540, ow, 120, "SCENE button (6 mm tact)",
                   "press fit in the face panel, internal pull-up"))
    p.append(pin(ox, my + 590, "", SIG))
    p.append(f'<circle cx="{ox + 40}" cy="{my + 660}" r="3.5" fill="{GND}"/>')
    p.append(text(ox + 48, my + 664, "GND", GND))
    p.append(gnd_symbol(ox + 40, my + 660))

    p.append(block(ox, my + 690, ow, 130, "Record indicator LED",
                   "3 mm red LED + 220 R series resistor"))
    p.append(pin(ox, my + 730, "", SIG))
    p.append(f'<circle cx="{ox + 40}" cy="{my + 820}" r="3.5" fill="{GND}"/>')
    p.append(text(ox + 48, my + 824, "GND", GND))
    p.append(gnd_symbol(ox + 40, my + 820))

    # ------------------------------------------------------------- wiring --
    for y, _label, color, name in signals:
        p.append(wire(mx + mw, my + y, ox, my + y, color))
        p.append(text((mx + mw + ox) / 2 - 30, my + y - 8, name, color, 11.5, "middle"))

    # ---------------------------------------------------------------- USB --
    p.append(block(mx, my + mh + 80, 320, 100, "USB-C (host computer)",
                   "5 V + GND + native CDC, 250 mA advertised"))
    p.append(wire(mx + 150, my + mh, mx + 150, my + mh + 80, GND))

    # -------------------------------------------------------------- notes --
    nx, ny = 1220, 150
    p.append(block(nx, ny, 340, 700, "Notes", ""))
    notes = [
        "1. USB-C is the only power and data source:",
        "   no battery, no radio, no mains input.",
        "2. The STEMMA QT connector of the QT Py is",
        "   I2C1: SDA = GPIO22, SCL = GPIO23.",
        "3. OLED connector order on both ends:",
        "   GND, 3V3, SDA, SCL (STEMMA QT standard).",
        "   The OLED sits on the STEMMA QT port of the",
        "   board, so display and MCU need only one",
        "   4 pin cable (product 4210, 100 mm).",
        "4. The two buttons and the LED are wired to",
        "   the castellated pads of the board with",
        "   22 AWG wire; they are mounted in the face",
        "   panel.",
        "5. Buttons use the internal pull-up of the",
        "   RP2040, so no external resistor is needed.",
        "6. LED current: (3.3 V - 2.0 V) / 220 R",
        "   = 5.9 mA.",
        "7. The red LED is driven from GPIO28 and is",
        "   only lit while the host confirms that OBS",
        "   is really recording.",
        "8. The panel buttons and the LED share the",
        "   GND of the board - one common wire each.",
    ]
    for i, line in enumerate(notes):
        p.append(text(nx + 16, ny + 80 + i * 23, line, MUTED, 12))

    p.append(text(40, H - 34,
                  "Sources: Adafruit 4900 / 938 / 367 / 777 - "
                  "Adafruit_QT_Py-RP2040-PCB (Eagle) - arduino-pico 6.4.0 "
                  "variants/adafruit_qtpy/pins_arduino.h", MUTED, 11.5))
    p.append("</svg>")
    return "\n".join(p)


def main():
    svg = build()
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(svg)
    print("wrote %s (%d bytes)" % (OUT, len(svg)))


if __name__ == "__main__":
    main()
